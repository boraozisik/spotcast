"""SpotCast web API (FastAPI).

Run with: uv run spotcast-api   →   open http://127.0.0.1:8000/docs
"""

import logging
import time
from collections.abc import AsyncIterator, Callable
from contextlib import asynccontextmanager
from datetime import datetime
from typing import Annotated, Any

import pandas as pd
import requests
from fastapi import Depends, FastAPI, HTTPException, Query, Request
from pydantic import BaseModel, Field
from sqlalchemy.exc import SQLAlchemyError

from spotcast.data import fetch_all_spots
from spotcast.db import get_engine
from spotcast.explain import (
    CAUTION,
    Explanation,
    Retriever,
    explain_recommendation,
)
from spotcast.llm import LLMOutputError, LLMUnavailableError, chat
from spotcast.locations import SPOTS
from spotcast.model import load_model, predict_conditions
from spotcast.profiles import PROFILES, ActivityProfile, get_profile
from spotcast.rag import SearchResult, search
from spotcast.recommend import Preferences, recommend
from spotcast.uncertainty import days_ahead, lead_time_note

logger = logging.getLogger("spotcast.api")

LLM_ATTEMPTS = 2  # a broken LLM answer is retried once before giving up

# Open-Meteo updates a few times a day; don't call it on every request
FORECAST_CACHE_SECONDS = 30 * 60


# ---------- Response shapes (like DTOs in NestJS) ----------


class SpotOut(BaseModel):
    name: str
    latitude: float
    longitude: float


class HourOut(BaseModel):
    spot: str
    time: datetime
    wind_kn: float
    wave_m: float
    is_day: bool
    prediction: str = Field(description='"good", "marginal" or "bad"')


class WindowOut(BaseModel):
    spot: str
    start: datetime
    end: datetime
    hours: int
    good_hours: int
    avg_wind_kn: float
    max_wave_m: float
    score: float
    warnings: list[str] = Field(
        default=[], description="Fixed warnings, e.g. a forecast too far ahead to trust"
    )


class RecommendOut(BaseModel):
    sport: str
    level: str
    generated_at: datetime
    windows: list[WindowOut] = Field(
        description="Best windows first. Empty if nothing fits."
    )


class SourceOut(BaseModel):
    id: int = Field(description="The number used in tips, e.g. [1]")
    title: str
    section: str
    source: str = Field(description="Where this information comes from")


class ExplainOut(RecommendOut):
    """Same as /recommend, plus a Turkish explanation written by the local LLM."""

    explanation: Explanation
    sources: list[SourceOut] = Field(description="Only the sources cited in the tips")
    caution: str = Field(description="Fixed safety text, never generated by the LLM")


# ---------- Forecast source with a small in-memory cache ----------


class ForecastCache:
    """Remembers the last forecast for a while, so many requests cause one API call."""

    def __init__(self, fetch: Callable[[], pd.DataFrame], max_age_seconds: float):
        self._fetch = fetch
        self._max_age = max_age_seconds
        self._data: pd.DataFrame | None = None
        self._fetched_at = 0.0

    def get(self) -> pd.DataFrame:
        if self._data is None or time.monotonic() - self._fetched_at > self._max_age:
            self._data = self._fetch()
            self._fetched_at = time.monotonic()
        return self._data


# ---------- App startup: load models once ----------


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    """Runs once when the server starts (like onModuleInit), not on every request."""
    app.state.bundle = load_model()  # one model for every profile
    app.state.forecast = ForecastCache(
        lambda: fetch_all_spots(SPOTS), FORECAST_CACHE_SECONDS
    )
    try:
        app.state.engine = get_engine()  # creates a pool; connects only when used
    except RuntimeError as error:
        logger.warning("No database, explanations will have no sources: %s", error)
        app.state.engine = None
    yield  # the server runs while we are paused here


app = FastAPI(
    title="SpotCast API",
    description="Is this spot good for my sport and level? Forecasts and recommendations.",
    version="0.1.0",
    lifespan=lifespan,
)


# ---------- Dependencies (like NestJS providers): easy to swap in tests ----------


def get_bundle(request: Request) -> dict[str, Any]:
    return request.app.state.bundle


def get_forecast(request: Request) -> pd.DataFrame:
    try:
        return request.app.state.forecast.get()
    except requests.RequestException as error:
        raise HTTPException(502, f"Weather service unavailable: {error}") from error


def get_now() -> datetime:
    return datetime.now()


def get_llm() -> Callable[..., Explanation]:
    return chat


def get_retriever(request: Request) -> Retriever:
    """Knowledge search for RAG. If it fails, explain without sources instead of failing."""
    engine = getattr(request.app.state, "engine", None)

    def retrieve(question: str, spots: list[str] | None) -> list[SearchResult]:
        if engine is None:
            return []
        try:
            return search(engine, question, k=3, spots=spots)
        except (SQLAlchemyError, LLMUnavailableError) as error:
            logger.warning(
                "Knowledge search failed, continuing without sources: %s", error
            )
            return []

    return retrieve


def resolve_profile(sport: str, level: str) -> ActivityProfile:
    try:
        return get_profile(sport, level)
    except ValueError as error:
        raise HTTPException(404, str(error)) from error


Bundle = Annotated[dict[str, Any], Depends(get_bundle)]
Forecast = Annotated[pd.DataFrame, Depends(get_forecast)]
Now = Annotated[datetime, Depends(get_now)]
LLM = Annotated[Callable[..., Explanation], Depends(get_llm)]
Retrieve = Annotated[Retriever, Depends(get_retriever)]
Sport = Annotated[str, Query(examples=["windsurf"])]
Level = Annotated[str, Query(examples=["intermediate"])]


def get_preferences(
    now: Now,
    earliest_hour: Annotated[int, Query(ge=0, le=23)] = 9,
    latest_hour: Annotated[int, Query(ge=0, le=23)] = 18,
    min_hours: Annotated[int, Query(ge=1, le=24)] = 2,
    weekend_only: bool = False,
    spots: Annotated[
        list[str] | None, Query(description="Limit to these spots")
    ] = None,
) -> Preferences:
    """Read the user's preferences from the query string. Shared by several endpoints."""
    if latest_hour < earliest_hour:
        raise HTTPException(
            422, "latest_hour must be the same as or after earliest_hour"
        )
    unknown = set(spots or []) - {s.name for s in SPOTS}
    if unknown:
        raise HTTPException(422, f"Unknown spots: {sorted(unknown)}")
    return Preferences(
        earliest_hour=earliest_hour,
        latest_hour=latest_hour,
        min_hours=min_hours,
        weekdays=frozenset({5, 6}) if weekend_only else None,
        spots=frozenset(spots) if spots else None,
        not_before=pd.Timestamp(now).ceil("h"),
    )


Prefs = Annotated[Preferences, Depends(get_preferences)]
Top = Annotated[int, Query(ge=1, le=20)]


def predicted_hours(
    sport: str, level: str, bundle: dict, forecast: pd.DataFrame
) -> tuple[ActivityProfile, pd.DataFrame]:
    profile = resolve_profile(sport, level)
    return profile, predict_conditions(bundle, forecast, profile)


# ---------- Endpoints ----------


@app.get("/health")
def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/spots")
def list_spots() -> list[SpotOut]:
    return [
        SpotOut(name=s.name, latitude=s.latitude, longitude=s.longitude) for s in SPOTS
    ]


@app.get("/profiles")
def list_profiles() -> list[dict[str, str]]:
    return [{"sport": sport, "level": level} for sport, level in PROFILES]


@app.get("/forecast")
def forecast_hours(
    sport: Sport, level: Level, bundle: Bundle, forecast: Forecast
) -> list[HourOut]:
    """Every hour of the next 7 days, for every spot, with the model's prediction."""
    _, predicted = predicted_hours(sport, level, bundle, forecast)
    return [
        HourOut(
            spot=row.spot,
            time=row.time,
            wind_kn=row.wind_speed_10m,
            wave_m=row.wave_height,
            is_day=row.is_day,
            prediction=row.prediction,
        )
        for row in predicted.itertuples()
    ]


def best_windows(
    sport: str,
    level: str,
    bundle: dict,
    forecast: pd.DataFrame,
    prefs: Preferences,
    top: int,
) -> tuple[ActivityProfile, pd.DataFrame]:
    profile, predicted = predicted_hours(sport, level, bundle, forecast)
    return profile, recommend(predicted, profile, prefs, top=top)


def to_window_list(best: pd.DataFrame, now: datetime) -> list[WindowOut]:
    rounded = best.round({"avg_wind_kn": 2, "max_wave_m": 2, "score": 2})
    windows = []
    for row in rounded.to_dict(orient="records"):
        note = lead_time_note(days_ahead(row["start"], now))
        windows.append(WindowOut(**row, warnings=[note] if note else []))
    return windows


@app.get("/recommend")
def recommend_windows(
    sport: Sport,
    level: Level,
    bundle: Bundle,
    forecast: Forecast,
    prefs: Prefs,
    now: Now,
    top: Top = 5,
) -> RecommendOut:
    """The best time windows in the next 7 days that fit your preferences."""
    profile, best = best_windows(sport, level, bundle, forecast, prefs, top)
    return RecommendOut(
        sport=profile.sport,
        level=profile.level,
        generated_at=now,
        windows=to_window_list(best, now),
    )


@app.get("/explain")
def explain_windows(
    sport: Sport,
    level: Level,
    bundle: Bundle,
    forecast: Forecast,
    prefs: Prefs,
    now: Now,
    llm: LLM,
    retrieve: Retrieve,
    top: Top = 3,
) -> ExplainOut:
    """Like /recommend, plus a short Turkish explanation from the local LLM (Ollama).

    Tips come from SpotCast's guides (RAG) and cite them by number.
    """
    profile, best = best_windows(sport, level, bundle, forecast, prefs, top)
    for attempt in range(1, LLM_ATTEMPTS + 1):
        try:
            result = explain_recommendation(
                best, profile, now, ask=llm, retrieve=retrieve
            )
            break
        except LLMUnavailableError as error:  # Ollama is off: trying again won't help
            raise HTTPException(503, str(error)) from error
        except LLMOutputError as error:  # a broken answer is often a one-off
            logger.warning("LLM answer invalid (attempt %d): %s", attempt, error)
            if attempt == LLM_ATTEMPTS:
                raise HTTPException(
                    502,
                    "The language model gave an invalid answer twice. "
                    "Try again, or use /recommend for the same windows without text.",
                ) from error

    return ExplainOut(
        sport=profile.sport,
        level=profile.level,
        generated_at=now,
        windows=to_window_list(best, now),
        explanation=result.explanation,
        sources=[
            SourceOut(id=s.id, title=s.title, section=s.section, source=s.source)
            for s in result.cited_sources
        ],
        caution=CAUTION,
    )


def run() -> None:
    """Start a development server that reloads when code changes."""
    import uvicorn

    uvicorn.run("spotcast.api:app", reload=True)
